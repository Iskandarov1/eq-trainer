// One-off build tool: subset Noto Sans to the app's alphabets and emit base64 JS
// modules importable from the bundle (fetch() of local assets fails on file://).
// Run: node scripts/build-fonts.mjs   (needs scripts/NotoSans-{Regular,Bold}.ttf)
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import subsetFont from 'subset-font'
import fontkit from '@pdf-lib/fontkit'

const here = path.dirname(fileURLToPath(import.meta.url))
const outDir = path.join(here, '..', 'src', 'fonts')
fs.mkdirSync(outDir, { recursive: true })

// ASCII + Latin-1 (é, «» etc.) + Latin Ext-A + Uzbek ʻ ʼ + Cyrillic + general
// punctuation (– — ‘ ’ “ ” … ). No ✓: Noto Sans LGC lacks U+2713 — PDFs render
// booleans as localized words instead.
const text =
  range(0x20, 0x7e) + range(0xa0, 0xff) + range(0x100, 0x17f) +
  'ʻʼ' + range(0x400, 0x4ff) + range(0x2010, 0x2027)

function range(a, b) {
  let s = ''
  for (let c = a; c <= b; c++) s += String.fromCodePoint(c)
  return s
}

// Codepoints the PDFs cannot work without — build fails loudly if any is missing
const REQUIRED = [0x02bb, 0x02bc, 0x0416, 0x044f, 0x00ab, 0x2014]

for (const weight of ['Regular', 'Bold']) {
  const src = fs.readFileSync(path.join(here, `NotoSans-${weight}.ttf`))
  const subset = await subsetFont(src, text, { targetFormat: 'truetype' })
  const font = fontkit.create(subset)
  for (const cp of REQUIRED) {
    if (!font.hasGlyphForCodePoint(cp)) {
      throw new Error(`U+${cp.toString(16)} missing from subsetted NotoSans-${weight}`)
    }
  }
  const b64 = subset.toString('base64')
  const js = `// Generated by scripts/build-fonts.mjs — do not edit.\n// Noto Sans ${weight} (SIL OFL 1.1), subsetted to Latin + Cyrillic + ʻʼ + punctuation.\nexport default '${b64}'\n`
  fs.writeFileSync(path.join(outDir, `notoSans${weight}.js`), js)
  console.log(`notoSans${weight}.js: ${subset.length} bytes ttf, ${js.length} bytes js`)
}
